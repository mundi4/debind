// Writes `Debind/DevStamp.lua`, naming the checkout the game is currently loading.
//
// A released build has its version stamped into the TOC by the packager; a working copy does not,
// and this is what stands in for it. The file is gitignored and its TOC line lives inside
// `#@debug@`, so nothing here can reach a user.
//
// Run by `.git/hooks/post-checkout` (see `dev-setup.md`), by `wow-link.js` for the worktree it
// links, and safe to run by hand. Worktrees share the common `.git` and so the hook, which runs
// with the worktree as its working directory and stamps that one. **A worktree Claude makes never
// fires it**: Claude creates it without a checkout and resets into it. Linking it is what stamps it.

const { execFileSync } = require("child_process");
const fs = require("fs");
const path = require("path");

// **The root comes from the directory passed in, never from this file's location.** Worktrees share
// one `.git`, so they also share the hook -- and `wow-link.js` runs this copy against another
// worktree. Deriving the root from `__dirname` made every worktree stamp the same file, with the
// same branch name, which is the one thing this must not do.
function git(cwd, ...args) {
    return execFileSync("git", args, { cwd, encoding: "utf8" }).trim();
}

// A worktree Claude made is named after its folder -- what `npm run link` calls it -- even when
// something other than its own branch is checked out in it. The owner's call: the folder name, not
// what is loaded.
//
// A detached HEAD has no branch name, which is the normal state of a worktree checked out at a
// release tag -- exactly the case where knowing what is loaded matters most. Name the tag, or the
// short sha when there is no tag.
function describeCheckout(root) {
    const parent = path.dirname(root);
    if (path.basename(parent) === "worktrees" && path.basename(path.dirname(parent)) === ".claude") {
        return path.basename(root);
    }
    const branch = git(root, "rev-parse", "--abbrev-ref", "HEAD");
    if (branch !== "HEAD") {
        return branch;
    }
    try {
        return git(root, "describe", "--tags", "--exact-match", "HEAD");
    } catch {
        return git(root, "rev-parse", "--short", "HEAD");
    }
}

// `root` has to be the top of a checkout and not merely inside one: `wow-link.js` also links a plain
// folder, and one sitting inside a checkout would have that checkout stamped instead.
function stamp(root) {
    root = path.resolve(root);
    if (path.relative(git(root, "rev-parse", "--show-toplevel"), root) !== "") {
        throw new Error(`${root} is not the top of a checkout`);
    }
    const target = path.join(root, "Debind", "DevStamp.lua");
    const label = describeCheckout(root);
    const body = `-- Generated by tools/stamp-dev.js. Not tracked; edits here are overwritten.
local _, DebindPrivate = ...;
DebindPrivate.DEV_STAMP = ${JSON.stringify(label)};
`;

    // Only write when it actually changed, so a checkout that did not move the branch does not touch
    // the file's mtime and make the addon look edited.
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== body) {
        fs.writeFileSync(target, body);
    }
    return label;
}

module.exports = { stamp };

if (require.main === module) {
    process.stdout.write(`${stamp(git(process.cwd(), "rev-parse", "--show-toplevel"))}\n`);
}
